# test_dns.sh — direct-path resolver list + per-domain DNS overrides. Sourced by run.sh.
#
# Covers the PURE parts of the DNS work: list parsing/defaults, the "saved
# choice must still be a member" rule in _active_dns_direct, override parsing,
# and the set-config validation gate. The live probe (_dns_probe) and the
# watchdog failover are NOT covered — they need a real resolver and a tunnel.

# Every assertion below mutates config.json, so start from a known fixture.
fresh_config '{"mode":"all_vpn"}'

# --- _dns_direct_list (core) — ordered list, comma separated, Yandex default ---
_t dns_direct_list
update_config '.dns_direct_servers = ""' >/dev/null 2>&1
assert_eq "dns-list-default" "$(_dns_direct_list)" "77.88.8.8 77.88.8.1"
update_config '.dns_direct_servers = "1.1.1.1,8.8.8.8"' >/dev/null 2>&1
assert_eq "dns-list-two"     "$(_dns_direct_list)" "1.1.1.1 8.8.8.8"
update_config '.dns_direct_servers = " 1.1.1.1 , 8.8.8.8 "' >/dev/null 2>&1
assert_eq "dns-list-spaces"  "$(_dns_direct_list)" "1.1.1.1 8.8.8.8"
update_config '.dns_direct_servers = "9.9.9.9"' >/dev/null 2>&1
assert_eq "dns-list-single"  "$(_dns_direct_list)" "9.9.9.9"

# --- _active_dns_direct (core) ---
# The persisted pick wins ONLY while it is still in the configured list —
# otherwise editing dns_direct_servers would be silently ignored until the next
# failover, leaving the generator emitting a resolver the user removed.
_t active_dns_direct
update_config '.dns_direct_servers = "1.1.1.1,8.8.8.8"' >/dev/null 2>&1
rm -f "$ECLIPVPN_TMP/dns_direct_active"
assert_eq "dns-active-first"    "$(_active_dns_direct)" "1.1.1.1"
echo "8.8.8.8" > "$ECLIPVPN_TMP/dns_direct_active"
assert_eq "dns-active-saved"    "$(_active_dns_direct)" "8.8.8.8"
echo "9.9.9.9" > "$ECLIPVPN_TMP/dns_direct_active"
assert_eq "dns-active-stale"    "$(_active_dns_direct)" "1.1.1.1"
echo "" > "$ECLIPVPN_TMP/dns_direct_active"
assert_eq "dns-active-empty"    "$(_active_dns_direct)" "1.1.1.1"
rm -f "$ECLIPVPN_TMP/dns_direct_active"

# --- _dns_overrides_pairs (core) — "domain=ip" pairs -> "domain<TAB>ip" lines ---
_t dns_overrides_pairs
update_config '.dns_overrides = ""' >/dev/null 2>&1
assert_eq "dns-ov-empty" "$(_dns_overrides_pairs | wc -l | tr -d ' ')" "0"
update_config '.dns_overrides = "vtb.ru=77.88.8.8"' >/dev/null 2>&1
assert_eq "dns-ov-one"   "$(_dns_overrides_pairs)" "$(printf 'vtb.ru\t77.88.8.8')"
update_config '.dns_overrides = "vtb.ru=77.88.8.8,sber.ru=77.88.8.1"' >/dev/null 2>&1
assert_eq "dns-ov-count" "$(_dns_overrides_pairs | wc -l | tr -d ' ')" "2"
update_config '.dns_overrides = "junk,vtb.ru=77.88.8.8"' >/dev/null 2>&1
assert_eq "dns-ov-skip-bad" "$(_dns_overrides_pairs | wc -l | tr -d ' ')" "1"

# --- set-config gate (config.sh) — every value is CGI-reachable ---
_t dns_set_config
cmd_set_config dns_direct_servers "1.1.1.1,8.8.8.8" >/dev/null 2>&1
assert_rc "dns-cfg-ok"        "$?" 0
cmd_set_config dns_direct_servers "1.1.1.1,999.1.1.1" >/dev/null 2>&1
assert_rc "dns-cfg-bad-ip"    "$?" 1
cmd_set_config dns_direct_servers "not-an-ip" >/dev/null 2>&1
assert_rc "dns-cfg-nonip"     "$?" 1
# A rejected value must not have been written — the old list must survive.
assert_eq "dns-cfg-atomic"    "$(_dns_direct_list)" "1.1.1.1 8.8.8.8"
cmd_set_config dns_direct_servers "off" >/dev/null 2>&1
assert_eq "dns-cfg-off"       "$(_dns_direct_list)" "77.88.8.8 77.88.8.1"

cmd_set_config dns_overrides "vtb.ru=77.88.8.8" >/dev/null 2>&1
assert_rc "dns-ov-cfg-ok"     "$?" 0
cmd_set_config dns_overrides "vtb.ru" >/dev/null 2>&1
assert_rc "dns-ov-cfg-nopair" "$?" 1
cmd_set_config dns_overrides "vtb.ru=notanip" >/dev/null 2>&1
assert_rc "dns-ov-cfg-badip"  "$?" 1
cmd_set_config dns_overrides 'ev"il.ru=1.1.1.1' >/dev/null 2>&1
assert_rc "dns-ov-cfg-quote"  "$?" 1
cmd_set_config dns_overrides '$(id).ru=1.1.1.1' >/dev/null 2>&1
assert_rc "dns-ov-cfg-subst"  "$?" 1
assert_eq "dns-ov-cfg-atomic" "$(_dns_overrides_pairs | wc -l | tr -d ' ')" "1"
cmd_set_config dns_overrides "off" >/dev/null 2>&1
assert_eq "dns-ov-cfg-off"    "$(_dns_overrides_pairs | wc -l | tr -d ' ')" "0"

# Leave the scratch config clean for any suite that runs after this one.
update_config '.dns_direct_servers = "" | .dns_overrides = ""' >/dev/null 2>&1

# --- generator: shape + determinism (singbox.sh) ---
# The cmd_restart unchanged-config fast path compares the GENERATED bytes, so
# the override block must be stable. group_by(.ip) orders the groups, but the
# domains inside a group came out in config-string order until `unique` was
# added — reordering the pairs then produced a different file and forced a
# pointless tunnel bounce. Locked in here.
_t dns_generator
fresh_config '{"mode":"all_vpn"}'
printf '%s\n' '[{"name":"t","host":"1.2.3.4","port":443,"protocol":"vless","uuid":"u"}]' \
    > "$ECLIPVPN_TMP/servers.json"
_gen() { generate_singbox_config "$1" all_vpn "$ECLIPVPN_TMP/servers.json" 0 1080 2>/dev/null; }

update_config '.dns_overrides = ""' >/dev/null 2>&1
_gen "$ECLIPVPN_TMP/g_plain.json"
assert_eq "gen-valid-plain"  "$(jq -e . "$ECLIPVPN_TMP/g_plain.json" >/dev/null 2>&1 && echo ok)" ok
assert_eq "gen-no-ov-server" "$(jq '[.dns.servers[]|select(.tag|startswith("dns-ov"))]|length' "$ECLIPVPN_TMP/g_plain.json")" 0

update_config '.dns_overrides = "vtb.ru=77.88.8.8,sber.ru=77.88.8.8,foo.com=1.1.1.1"' >/dev/null 2>&1
_gen "$ECLIPVPN_TMP/g_a.json"
assert_eq "gen-valid-ov"   "$(jq -e . "$ECLIPVPN_TMP/g_a.json" >/dev/null 2>&1 && echo ok)" ok
# two distinct resolvers -> two servers, and the two domains sharing one are merged
assert_eq "gen-ov-servers" "$(jq '[.dns.servers[]|select(.tag|startswith("dns-ov"))]|length' "$ECLIPVPN_TMP/g_a.json")" 2
assert_eq "gen-ov-merged"  "$(jq -c '[.dns.rules[]|select(.server=="dns-ov-1").domain_suffix]|flatten' "$ECLIPVPN_TMP/g_a.json")" '["sber.ru","vtb.ru"]'
# overrides must be the FIRST dns rules — they outrank force-VPN / geosite-ru
assert_eq "gen-ov-first"   "$(jq -r '.dns.rules[0].server' "$ECLIPVPN_TMP/g_a.json" | cut -c1-6)" "dns-ov"

# same config -> byte-identical
_gen "$ECLIPVPN_TMP/g_b.json"
cmp -s "$ECLIPVPN_TMP/g_a.json" "$ECLIPVPN_TMP/g_b.json"
assert_rc "gen-stable" "$?" 0
# reordered config string -> STILL byte-identical
update_config '.dns_overrides = "foo.com=1.1.1.1,sber.ru=77.88.8.8,vtb.ru=77.88.8.8"' >/dev/null 2>&1
_gen "$ECLIPVPN_TMP/g_c.json"
cmp -s "$ECLIPVPN_TMP/g_a.json" "$ECLIPVPN_TMP/g_c.json"
assert_rc "gen-order-agnostic" "$?" 0

# the failover choice reaches the generated dns-direct server
update_config '.dns_direct_servers = "1.1.1.1,8.8.8.8" | .dns_overrides = ""' >/dev/null 2>&1
echo "8.8.8.8" > "$ECLIPVPN_TMP/dns_direct_active"
_gen "$ECLIPVPN_TMP/g_d.json"
assert_eq "gen-active-direct" "$(jq -r '.dns.servers[]|select(.tag=="dns-direct").server' "$ECLIPVPN_TMP/g_d.json")" "8.8.8.8"
rm -f "$ECLIPVPN_TMP/dns_direct_active"
update_config '.dns_direct_servers = "" | .dns_overrides = ""' >/dev/null 2>&1
